/**
 * Inline the card fonts as base64 so the OG route never reads the filesystem.
 *
 * Serverless bundles do not reliably carry repo assets that are read at render
 * time, and a missing font is a 500 for every social card. Generating the module
 * in prebuild keeps the route self-contained and still versioned by the fonts.
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import path from 'node:path'

const OUT = path.join(process.cwd(), 'lib', 'og-fonts.generated.mjs')
const FONTS = {
  inter400: 'inter-400.ttf',
  inter600: 'inter-600.ttf',
  archivo600: 'archivo-600.ttf',
  newsreader500: 'newsreader-500.ttf',
}

const parts = Object.entries(FONTS).map(([key, file]) => {
  const bytes = readFileSync(path.join(process.cwd(), 'assets', 'fonts', file))
  return `  ${key}: '${bytes.toString('base64')}',`
})

mkdirSync(path.dirname(OUT), { recursive: true })
writeFileSync(OUT, `// Generated by scripts/build-og-fonts.mjs. Do not edit.\nexport const OG_FONTS = {\n${parts.join('\n')}\n}\n`)
console.log(`og-fonts: wrote ${Object.keys(FONTS).length} faces to lib/og-fonts.generated.mjs`)
