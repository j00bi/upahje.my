/**
 * Freeze the data each social card needs, so the card route never touches the
 * filesystem at render time. A serverless bundle that is missing the corpus is a
 * 500 on every card; a generated module cannot go missing.
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { allArticles, formatDate } from '../lib/articles.mjs'
import { TOPIC_MAPPING, TOPICS } from '../lib/topics.mjs'

const OUT = path.join(process.cwd(), 'lib', 'og-data.generated.mjs')

const topics = Object.fromEntries(TOPICS.map((topic) => [topic.slug, { en: topic.en, ms: topic.ms }]))
const entries = {}

for (const lang of ['en', 'ms']) {
  for (const article of allArticles(lang)) {
    const map = TOPIC_MAPPING[article.translationKey] || null
    const verified = article.sources.map((source) => source.checked).filter(Boolean).sort().pop() || null
    entries[`${lang}/${article.slug}`] = {
      title: article.title,
      topic: map ? map.topic : null,
      checked: { en: verified ? formatDate(verified, 'en') : null, ms: verified ? formatDate(verified, 'ms') : null },
    }
  }
}

writeFileSync(
  OUT,
  `// Generated by scripts/build-og-data.mjs. Do not edit.\nexport const OG_TOPICS = ${JSON.stringify(topics)}\nexport const OG_DATA = ${JSON.stringify(entries)}\n`,
)
console.log(`og-data: wrote ${Object.keys(entries).length} cards and ${Object.keys(topics).length} topic labels`)
