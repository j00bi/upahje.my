/**
 * Freeze the data each social card needs, so the card route never touches the
 * filesystem at render time. A serverless bundle that is missing the corpus is a
 * 500 on every card; a generated module cannot go missing.
 */
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { allArticles } from '../lib/articles.mjs'
import { TOPIC_MAPPING } from '../lib/topics.mjs'

const OUT = path.join(process.cwd(), 'lib', 'og-data.generated.mjs')
const entries = {}

for (const article of allArticles('en')) {
  const map = TOPIC_MAPPING[article.translationKey] || null
  const verified = article.sources
    .map((source) => source.checked)
    .filter(Boolean)
    .sort()
    .pop() || null
  entries[`${article.lang}/${article.slug}`] = {
    title: article.title,
    topic: map ? map.topic : null,
    verified,
    draft: Boolean(article.draft),
  }
}
for (const article of allArticles('ms')) {
  const map = TOPIC_MAPPING[article.translationKey] || null
  const verified = article.sources
    .map((source) => source.checked)
    .filter(Boolean)
    .sort()
    .pop() || null
  entries[`${article.lang}/${article.slug}`] = {
    title: article.title,
    topic: map ? map.topic : null,
    verified,
    draft: Boolean(article.draft),
  }
}

writeFileSync(OUT, `// Generated by scripts/build-og-data.mjs. Do not edit.\nexport const OG_DATA = ${JSON.stringify(entries, null, 0)}\n`)
console.log(`og-data: wrote ${Object.keys(entries).length} cards to lib/og-data.generated.mjs`)
